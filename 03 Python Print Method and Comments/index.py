# ==========================================
# 1. PYTHON PRINT METHOD
# ==========================================

# Basic print statement with double quotes
print("Hello World")

# Print statement with single quotes
print('Hello World')

# Printing multiple arguments (separated by a comma)
# Python automatically adds a space between the arguments
print("Hello", "World")

# Printing a number (integer)
print(25)

# Printing a combination of text and numbers
print("My favorite number is", 7)


# ==========================================
# 2. PYTHON COMMENTS
# ==========================================

# This is a single-line comment. It starts with a hashtag (#).

print("This line has an inline comment")  # This is an inline comment

# Multi-line comments use triple quotes (either """ or ''').
# They are useful for writing detailed explanations or documentation.

"""
This is a multi-line comment.
It spans across multiple lines.
The Python interpreter will completely ignore this block of text.
"""

print("Comments are ignored by Python!")

